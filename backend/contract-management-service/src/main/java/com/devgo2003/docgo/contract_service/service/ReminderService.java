    public Reminder createReminder(String contractId, String title, String description, 
                                 Reminder.ReminderType reminderType, LocalDateTime scheduledAt) {
        Contract contract = contractRepository.findById(contractId)
                .orElseThrow(() -> new RuntimeException("Contract not found"));
        
        Reminder reminder = new Reminder(contract, title, description, reminderType, scheduledAt);
        reminder.setContractId(contractId);
        reminder.initializeNewEntity();
        
        return reminderRepository.save(reminder);
    }

